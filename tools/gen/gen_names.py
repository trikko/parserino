#!/usr/bin/env python3
"""Generates source/parserino/names.d and source/parserino/html/entities.d.
Inputs: names_gen.txt (tag names, categories, attribute names) and entities.tsv
(name -> UTF-8 hex), both extracted once from the lexbor tables."""
import sys

names_file, entities_file, out_dir = sys.argv[1:4]

tags, attrs, section = [], [], None
for line in open(names_file):
    line = line.rstrip('\n')
    if line in ('TAGS', 'ATTRS'): section = line; continue
    parts = line.split('\t')
    if section == 'TAGS': tags.append((parts[1], [int(x) for x in parts[2].split(',') if x]))
    else: attrs.append(parts[1])

special = {'#undef': 'Undef', '#end-of-file': 'EndOfFile', '#text': 'TextNode', '#document': 'DocumentNode',
           '!--': 'CommentNode', '!doctype': 'DoctypeNode', '?ProcessingInstruction': 'ProcessingInstructionNode'}

def ident(n):
    """The enum member of a name, in PascalCase: `annotation-xml` -> `AnnotationXml`"""
    if n in special: return special[n]
    return ''.join(p[0].upper() + p[1:] for p in n.replace('_', '-').split('-') if p)

def dstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

o = []
o.append('''/++
 Names of tags, attributes and namespaces.

 Known names have a fixed id (`Tag`, `AttrName`); other names get an id when a
 document meets them (see `NameTable`). Generated by tools/gen/gen_names.py
 (the lists come from lexbor, Apache-2.0: see NOTICE-lexbor).
+/
module parserino.names;

import parserino.arena;

@nogc nothrow pure @safe:

/// Namespaces
enum Ns : ubyte
{
    None, Any, Html, Math, Svg, Xlink, Xml, Xmlns,
}

/// Known tags. Unknown tag names get ids from `Tag.Last` on.
enum Tag : uint
{
''')
for i, (n, _) in enumerate(tags):
    o.append('    %s = %d,\n' % (ident(n), i))
o.append('    Last = %d,\n}\n\n' % len(tags))

o.append('/// Names of the known tags (lowercase)\nimmutable string[Tag.Last] tagNames = [\n')
for n, _ in tags: o.append('    %s,\n' % dstr(n))
o.append('];\n\n')

o.append('''/// Categories of the tags in the tree construction ("special", "formatting", scopes, ...)
enum Category : ubyte
{
    Ordinary = 0x01,
    Special = 0x02,
    Formatting = 0x04,
    Scope = 0x08,
    ScopeListItem = 0x10,
    ScopeButton = 0x20,
    ScopeTable = 0x40,
}

/// Categories of each tag, for each namespace
immutable ubyte[Ns.max + 1][Tag.Last] tagCategories = [
''')
for n, c in tags: o.append('    [%s],\n' % ', '.join(str(x) for x in c))
o.append('];\n\n')

o.append('/// Known attributes. Unknown names get ids from `AttrName.Last` on.\nenum AttrName : uint\n{\n')
for i, n in enumerate(attrs):
    o.append('    %s = %d,\n' % ('Undef' if n == '#undef' else ident(n), i))
o.append('    Last = %d,\n}\n\n' % len(attrs))
o.append('/// Names of the known attributes\nimmutable string[AttrName.Last] attrNames = [\n')
for n in attrs: o.append('    %s,\n' % dstr(n))
o.append('];\n')

o.append('''
/// Id of a known tag (`name` must be lowercase), or `Tag.Undef`
Tag knownTag(scope const(char)[] name) @trusted { return cast(Tag) staticLookup!tagNames(name); }

/// Id of a known attribute (`name` must be lowercase), or `AttrName.Undef`
AttrName knownAttr(scope const(char)[] name) @trusted { return cast(AttrName) staticLookup!attrNames(name); }

///
unittest
{
    assert(knownTag("div") == Tag.Div);
    assert(knownTag("template") == Tag.Template);
    assert(knownTag("nope") == Tag.Undef);
    assert(knownAttr("href") == AttrName.Href);
    static assert(knownTag("svg") == Tag.Svg);
}

/++ Interned names of a document: known names have their static id, the others
 + get new ids (from `first` on) the first time they are seen.
 +/
struct NameTable
{
@nogc nothrow pure @safe:
    @disable this(this);

    /// Id of `name`, adding it if needed. It returns 0 if out of memory.
    uint intern(scope const(char)[] name, ref Arena arena, uint first)
    {
        if (auto id = find(name, first)) return id;

        // A null name marks the empty slots: the empty name is a non-null ""
        const(char)[] copy = name.length ? arena.dup(name) : "";
        if (copy is null) return 0;

        if ((count + 1) * 2 > slots.length && !grow()) return 0;

        names.put(copy);
        if (names.failed) return 0;
        insert(Entry(copy, first + cast(uint) count), hash(name));
        count++;
        return first + cast(uint) count - 1;
    }

    /// Id of `name` if already interned, else 0
    uint find(scope const(char)[] name, uint first) const
    {
        if (slots.length == 0) return 0;

        auto mask = slots.length - 1;
        for (auto i = hash(name) & mask; slots[i].name !is null; i = (i + 1) & mask)
            if (slots[i].name == name) return slots[i].id;

        return 0;
    }

    /// Name of an id (from `first` on)
    const(char)[] name(uint id, uint first) const { return names[id - first]; }

    ~this() @trusted
    {
        import core.memory : pureFree;
        if (!__ctfe && slots.ptr !is null) pureFree(slots.ptr);
    }

    private:

    static struct Entry { const(char)[] name; uint id; }

    Entry[] slots;
    Buffer!(const(char)[]) names;
    size_t count;

    void insert(Entry e, size_t h)
    {
        auto mask = slots.length - 1;
        auto i = h & mask;
        while (slots[i].name !is null) i = (i + 1) & mask;
        slots[i] = e;
    }

    bool grow() @trusted
    {
        import core.memory : pureCalloc, pureFree;

        auto n = slots.length == 0 ? 64 : slots.length * 2;
        Entry[] ns;
        if (__ctfe) ns = new Entry[n];
        else
        {
            auto p = cast(Entry*) pureCalloc(n, Entry.sizeof);
            if (p is null) return false;
            ns = p[0 .. n];
        }

        auto old = slots;
        slots = ns;
        foreach (ref e; old) if (e.name !is null) insert(e, hash(e.name));
        if (!__ctfe && old.ptr !is null) pureFree(old.ptr);
        return true;
    }
}

/// FNV-1a
size_t hash(scope const(char)[] s)
{
    uint h = 2166136261;
    foreach (c; s) { h ^= c; h *= 16777619; }
    return h;
}

private:

// A static hash table (built at compile time) from a list of names to their index
template staticLookup(alias names)
{
    enum size_t size = () {
        size_t n = 1;
        while (n < names.length * 4) n *= 2;
        return n;
    }();

    static immutable ushort[size] table = () {
        ushort[size] t;
        foreach (i, n; names)
        {
            if (i == 0) continue;
            auto j = hash(n) & (size - 1);
            while (t[j] != 0) j = (j + 1) & (size - 1);
            t[j] = cast(ushort) i;
        }
        return t;
    }();

    uint staticLookup(scope const(char)[] name)
    {
        for (auto j = hash(name) & (size - 1); table[j] != 0; j = (j + 1) & (size - 1))
            if (names[table[j]] == name) return table[j];
        return 0;
    }
}
''')
open(out_dir + '/names.d', 'w').write(''.join(o))

# entities
ents = []
for line in open(entities_file):
    n, h = line.rstrip('\n').split('\t')
    ents.append((n, bytes.fromhex(h)))
ents.sort(key=lambda e: e[0].encode())
e = []
e.append('''/++
 Named character references of HTML (`&amp;`, `&nbsp;`, ...).
 Generated by tools/gen/gen_names.py (the list comes from lexbor, Apache-2.0: see NOTICE-lexbor).
+/
module parserino.html.entities;

@nogc nothrow pure @safe:

struct Entity
{
    string name;    /// without '&', with the ';' when it has one
    string value;   /// UTF-8
}

/// All the named character references, sorted by name
static immutable Entity[] entities = [
''')
def esc(b):
    return '"' + ''.join('\\x%02x' % c for c in b) + '"'
for n, v in ents: e.append('    Entity(%s, %s),\n' % (dstr(n), esc(v)))
e.append('''];

/++ Incremental matching of a name, one char at a time: `entities[lo .. hi]` are the
 + names starting with the chars seen so far. It works across input chunks.
 +/
struct EntityMatcher
{
@nogc nothrow pure @safe:
    size_t lo = 0, hi = entities.length;
    size_t depth;       /// chars seen
    size_t best = size_t.max;   /// the longest full match so far (index in `entities`)
    size_t bestLength;  /// its length

    /// Feed one char. It returns false when no name can match anymore.
    bool put(char c)
    {
        // Narrow [lo, hi) to the names with `c` at position `depth`
        size_t a = lo, b = hi;
        while (a < b)
        {
            auto m = (a + b) / 2;
            auto n = entities[m].name;
            if (n.length <= depth || n[depth] < c) a = m + 1; else b = m;
        }
        size_t first = a;
        b = hi;
        while (a < b)
        {
            auto m = (a + b) / 2;
            auto n = entities[m].name;
            if (n.length > depth && n[depth] <= c) a = m + 1; else b = m;
        }

        lo = first;
        hi = a;
        depth++;
        if (lo == hi) return false;

        if (entities[lo].name.length == depth) { best = lo; bestLength = depth; }
        return true;
    }
}

///
unittest
{
    EntityMatcher m;
    foreach (char c; "notin;") if (!m.put(c)) break;
    assert(entities[m.best].name == "notin;");
    assert(entities[m.best].value == "\\u2209");

    EntityMatcher m2;
    foreach (char c; "notit;") if (!m2.put(c)) break;
    assert(entities[m2.best].name == "not");
}
''')
open(out_dir + '/html/entities.d', 'w').write(''.join(e))
print(len(tags), 'tags', len(attrs), 'attrs', len(ents), 'entities')
